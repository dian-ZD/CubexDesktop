import { _electron as electron } from '@playwright/test'
import { cp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const source = join(tmpdir(), 'cubex-repro')
const dir = join(tmpdir(), 'cubex-ui-shell')
await rm(dir, { recursive: true, force: true })
await cp(source, dir, { recursive: true })
const app = await electron.launch({ args: ['.', `--user-data-dir=${dir}`] })
const page = await app.firstWindow()
page.on('pageerror', (err) => console.log('[pageerror]', err.message))
await page.waitForSelector('.shell')
await page.waitForTimeout(800)
const log = (...args) => console.log(...args)
const win = (fn) => app.evaluate(({ BrowserWindow }, body) => new Function('w', body)(BrowserWindow.getAllWindows()[0]), fn)
const shellClass = () => page.locator('.shell').getAttribute('class')

log('窗口透明', await win('return w.isMaximized() === false && w.getBackgroundColor()'))
log('圆角样式', await page.locator('.shell').evaluate((el) => getComputedStyle(el).borderRadius))
log('滚动条宽度', await page.evaluate(() => { const s = document.createElement('style'); return !!s; }))
await page.screenshot({ path: join(dir, '1-rounded.png') })

await page.getByLabel('最大化').click()
await page.waitForTimeout(500)
log('主进程已最大化', await win('return w.isMaximized()'))
log('渲染层 class', await shellClass())
log('还原按钮存在', await page.getByLabel('还原').count())
log('最大化后圆角', await page.locator('.shell').evaluate((el) => getComputedStyle(el).borderRadius))
await page.getByLabel('还原').click()
await page.waitForTimeout(500)
log('还原后 class', await shellClass())

const first = await page.locator('.thread-item').first()
if (await first.count()) {
  await first.locator('.task-row').click()
  await page.waitForTimeout(400)
  log('右栏显示', await page.locator('.right-panel').count())
  await page.screenshot({ path: join(dir, '2-right-panel.png') })
  await page.getByLabel('收起右栏').first().click()
  await page.waitForTimeout(300)
  log('收起后右栏', await page.locator('.right-panel').count())
  await page.getByLabel('展开右栏').click()
  await page.waitForTimeout(300)
  log('再展开右栏', await page.locator('.right-panel').count())
  await page.getByLabel('收起侧栏').click()
  await page.waitForTimeout(300)
  log('收起后左栏', await page.locator('.sidebar').count())
  await page.screenshot({ path: join(dir, '3-both-toggled.png') })
} else log('无任务，跳过右栏检查')
await app.close()
